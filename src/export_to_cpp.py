from pathlib import Path

import joblib
import numpy as np

# ============================================================
# CONFIGURATION
# ============================================================

PROJECT_DIR = Path(__file__).resolve().parent.parent

MODEL_PATH = PROJECT_DIR / "model" / "random_forest.joblib"
OUTPUT_PATH = PROJECT_DIR / "model" / "forest_model.h"

EXPECTED_FEATURES = [
    "soil_moisture_vwc_pct",
    "accel_vib_rms_g",
    "accel_peak_mag_g",
    "tilt_pitch_deg",
    "tilt_roll_deg",
]

EXPECTED_CLASSES = [0, 1, 2]

# ============================================================
# LOAD TRAINED MODEL
# ============================================================

if not MODEL_PATH.exists():
    raise FileNotFoundError(
        f"Model not found: {MODEL_PATH}\n"
        "Run python src/train_model.py first."
    )

bundle = joblib.load(MODEL_PATH)

model = bundle["model"]
features = bundle["features"]
class_names = bundle["class_names"]

if features != EXPECTED_FEATURES:
    raise ValueError(
        "Feature order mismatch.\n"
        f"Expected: {EXPECTED_FEATURES}\n"
        f"Received: {features}"
    )

if list(model.classes_) != EXPECTED_CLASSES:
    raise ValueError(
        f"Expected classes {EXPECTED_CLASSES}; "
        f"received {list(model.classes_)}"
    )

# ============================================================
# PREPARE C++ HEADER
# ============================================================

lines = [
    "#pragma once",
    "#include <stdint.h>",
    "",
    "// Automatically generated from random_forest.joblib.",
    "// Do not edit this file manually.",
    "// Feature order:",
    "// 0: Soil moisture VWC (%)",
    "// 1: Vibration RMS (g)",
    "// 2: Peak vibration magnitude (g)",
    "// 3: Pitch (degrees)",
    "// 4: Roll (degrees)",
    "",
    "namespace HazardModel {",
    "",
    "struct Node {",
    "    int16_t left;",
    "    int16_t right;",
    "    int16_t feature;",
    "    float threshold;",
    "    float p0;",
    "    float p1;",
    "    float p2;",
    "};",
    "",
    f"constexpr int NUM_TREES = {len(model.estimators_)};",
    "constexpr int NUM_FEATURES = 5;",
    "constexpr int NUM_CLASSES = 3;",
    "",
]

total_nodes = 0
node_counts = []

# ============================================================
# EXPORT EACH DECISION TREE
# ============================================================

for tree_index, estimator in enumerate(model.estimators_):

    tree = estimator.tree_
    node_counts.append(tree.node_count)

    # int16_t child indices require node indices to fit.
    if tree.node_count > 32767:
        raise ValueError(
            f"Tree {tree_index} has too many nodes for int16_t."
        )

    lines.append(
        f"static const Node tree_{tree_index}[] = {{"
    )

    for node_index in range(tree.node_count):

        left = int(tree.children_left[node_index])
        right = int(tree.children_right[node_index])

        # Scikit-learn stores leaf class values in model.classes_
        # order, which was verified above as [0, 1, 2].
        counts = np.asarray(
            tree.value[node_index][0],
            dtype=np.float64,
        )

        total = float(counts.sum())

        if total > 0:
            probabilities = counts / total
        else:
            probabilities = np.array([1.0, 0.0, 0.0])

        if left == -1 and right == -1:
            # Leaf node.
            feature_index = -1
            threshold = 0.0
            left = -1
            right = -1

        else:
            # Internal decision node.
            feature_index = int(tree.feature[node_index])
            threshold = float(tree.threshold[node_index])

            if not 0 <= feature_index < len(EXPECTED_FEATURES):
                raise ValueError(
                    f"Invalid feature index {feature_index} "
                    f"in tree {tree_index}, node {node_index}"
                )

        p0, p1, p2 = probabilities.tolist()

        def cpp_float(value):
            text = f"{float(value):.9g}"

            # C++ requires a decimal point or exponent before a float suffix.
            if "." not in text and "e" not in text.lower():
                text += ".0"

            return text + "f"


        lines.append(
            f"    {{{left}, {right}, {feature_index}, "
            f"{cpp_float(threshold)}, "
            f"{cpp_float(p0)}, "
            f"{cpp_float(p1)}, "
            f"{cpp_float(p2)}}},"
        )

        total_nodes += 1

    lines.append("};")
    lines.append("")

# ============================================================
# EXPORT TREE POINTER REGISTRY
# ============================================================

lines.append("static const Node* const FOREST_TREES[] = {")

for tree_index in range(len(model.estimators_)):
    lines.append(f"    tree_{tree_index},")

lines.append("};")
lines.append("")

# ============================================================
# EXPORT NODE COUNTS
# ============================================================

lines.append("static const int FOREST_NODE_COUNTS[] = {")

for count in node_counts:
    lines.append(f"    {count},")

lines.append("};")
lines.append("")

# ============================================================
# CLASS LABEL DOCUMENTATION
# ============================================================

lines.extend([
    "// Class 0: Lower Chance of Landslide",
    "// Class 1: Lookout for Landslide",
    "// Class 2: High Risk for Landslide",
    "",
    "}  // namespace HazardModel",
    "",
])

# ============================================================
# WRITE HEADER
# ============================================================

OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)

OUTPUT_PATH.write_text(
    "\n".join(lines),
    encoding="utf-8",
)

# ============================================================
# REPORT
# ============================================================

print("=" * 60)
print("RANDOM FOREST C++ EXPORT COMPLETE")
print("=" * 60)

print("\nSource model:")
print(MODEL_PATH)

print("\nGenerated header:")
print(OUTPUT_PATH)

print("\nModel information:")
print("Trees:", len(model.estimators_))
print("Features:", len(features))
print("Classes:", len(EXPECTED_CLASSES))
print("Total nodes:", total_nodes)

print("\nFeature order:")

for index, feature in enumerate(features):
    print(f"{index}: {feature}")

print("\nClass meanings:")

for class_id in EXPECTED_CLASSES:
    print(f"{class_id}: {class_names[class_id]}")

print("\nNode count range:")
print("Minimum:", min(node_counts))
print("Maximum:", max(node_counts))

print("\nGenerated arrays:")
print("Node arrays: tree_0 through tree_99")
print("Tree registry: FOREST_TREES")
print("Node registry: FOREST_NODE_COUNTS")

print("\nNext step: validate C++ predictions against Python.")